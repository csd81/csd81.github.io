#!/usr/bin/env node
// classify-namespace.mjs — walk the whole MATLAB install and split every .m-backed function into
// `real_m` (transparent algorithm we can port + parity-test) vs `mupad` (thin wrapper that marshals
// into the closed MuPAD CAS — opaque, must be implemented from scratch in TS). Compiled built-ins
// have NO .m file, so they are simply absent here and are enumerated separately via exist()==5.
//
// Output: scratch/classification.tsv  (name  class  toolbox  path)
//         docs/function-classification.md  (per-toolbox counts + full MuPAD list)
import { readFileSync, writeFileSync, mkdirSync, readdirSync, statSync } from 'node:fs';
import { resolve, dirname, basename, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const ML = process.argv[2] || '/usr/local/MATLAB/R2026a/toolbox';
const SKIP = /(^|\/)(private|test|tests|unittest|examples?|demos?|resources|derived|compiler|\+internal|\+coder|html|ja|ko_KR|zh_CN|de|es|fr|it|pt_BR|ru)(\/|$)/;
const MUPAD = /mupadmex|symengine|mupadmexnout|evalin\(\s*symengine/;

function walk(dir, out) {
  let ents;
  try { ents = readdirSync(dir, { withFileTypes: true }); } catch { return; }
  for (const e of ents) {
    const p = dir + sep + e.name;
    if (e.isDirectory()) { if (!SKIP.test(p)) walk(p, out); }
    else if (e.name.endsWith('.m') && e.name !== 'Contents.m') out.push(p);
  }
}

console.error(`walking ${ML} ...`);
const files = []; walk(ML, files);
console.error(`found ${files.length} .m files; classifying ...`);

const rows = [];                 // {name, cls, toolbox, path}
const seen = new Set();
for (const p of files) {
  const name = basename(p, '.m');
  if (/^[A-Z]/.test(name) && !p.includes('@')) { /* keep — some real fns are capitalized */ }
  const parts = p.split(sep);
  const ti = parts.indexOf('toolbox');
  const toolbox = ti >= 0 && parts[ti + 1] ? parts[ti + 1] : '?';
  let src = '';
  try { src = readFileSync(p, 'utf8'); } catch { continue; }
  if (!/^\s*function\b/m.test(src)) continue;          // skip scripts/help-only
  const cls = MUPAD.test(src) ? 'mupad' : 'real_m';
  const key = `${toolbox}/${name}`;
  if (seen.has(key)) continue; seen.add(key);
  rows.push({ name, cls, toolbox, path: p });
}

mkdirSync(`${ROOT}/scratch`, { recursive: true });
writeFileSync(`${ROOT}/scratch/classification.tsv`, rows.map((r) => `${r.name}\t${r.cls}\t${r.toolbox}\t${r.path}`).join('\n') + '\n');

// per-toolbox counts
const tb = new Map();
for (const r of rows) {
  const t = tb.get(r.toolbox) || { real_m: 0, mupad: 0 };
  t[r.cls]++; tb.set(r.toolbox, t);
}
const mupadRows = rows.filter((r) => r.cls === 'mupad');
const totReal = rows.filter((r) => r.cls === 'real_m').length;

let md = `# MATLAB function classification (.m-backed)\n\n`;
md += `Generated by \`scripts/classify-namespace.mjs\` over \`${ML}\`. Compiled built-ins have no .m\n`;
md += `file and are enumerated separately via \`exist()==5\`. **real_m** = transparent algorithm\n`;
md += `(port + parity-test). **mupad** = thin wrapper into the closed MuPAD CAS (opaque → implement\n`;
md += `the CAS logic in TS).\n\n`;
md += `- Total .m-backed functions: **${rows.length}**  (real_m **${totReal}**, mupad **${mupadRows.length}**)\n\n`;
md += `## Per-toolbox counts (toolboxes with any MuPAD, then largest)\n\n| toolbox | real_m | mupad |\n|---|---:|---:|\n`;
const order = [...tb.entries()].sort((a, b) => (b[1].mupad - a[1].mupad) || (b[1].real_m - a[1].real_m));
for (const [t, c] of order.slice(0, 40)) md += `| ${t} | ${c.real_m} | ${c.mupad} |\n`;
md += `\n## Full MuPAD (opaque-CAS) function list — the symbolic implementation frontier\n\n`;
const byTb = new Map();
for (const r of mupadRows) { (byTb.get(r.toolbox) || byTb.set(r.toolbox, []).get(r.toolbox)).push(r.name); }
for (const [t, names] of [...byTb.entries()].sort((a, b) => b[1].length - a[1].length)) {
  md += `**${t}** (${names.length}): ${[...new Set(names)].sort().join(', ')}\n\n`;
}
mkdirSync(`${ROOT}/docs`, { recursive: true });
writeFileSync(`${ROOT}/docs/function-classification.md`, md);
console.error(`classified ${rows.length} fns → scratch/classification.tsv`);
console.error(`real_m ${totReal} | mupad ${mupadRows.length} | docs/function-classification.md written`);
